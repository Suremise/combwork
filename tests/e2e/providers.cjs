// Visual check of the provider screens on a fresh profile: banner, Settings → Providers, Provider Setup, Add Agent.
const lib = require('./lib.cjs')
const { _electron } = require('playwright-core')
const fs = require('fs')
const path = require('path')
const scratch = lib.WORK
const userData = path.join(scratch, 'pv-profile')
const ws = path.join(scratch, 'pv-ws')
const HUNG_MS = lib.timing('hang.ui')
const results = []
const check = (name, ok, extra = '') => results.push(`${ok ? 'PASS' : 'FAIL'} ${name}${ok || !extra ? '' : ` (${extra})`}`)

;(async () => {
  for (const d of [userData, ws]) fs.rmSync(d, { recursive: true, force: true })
  fs.mkdirSync(path.join(ws, 'demo'), { recursive: true })
  const env = lib.combworkEnv({ CW_USER_DATA: userData, CW_API_PORT: lib.port(47893) })
  const app = await _electron.launch({ executablePath: lib.ELECTRON, args: [lib.ROOT], env })
  const page = await app.firstWindow()
  page.on('pageerror', (e) => results.push(`PAGEERROR ${e.message}`))
  await lib.fitWindow(app, page, { width: 1400, height: 850 })
  await lib.appReady(page)
  const inv = (ch, ...a) => page.evaluate(([c, x]) => window.combwork.invoke(c, ...x), [ch, a])
  /** Runs a command from the palette by what its row says: opened, typed, its row picked, then Enter. */
  const fromPalette = async (label) => {
    await page.keyboard.press('Control+Shift+P')
    await lib.until(async () => (await page.locator('.palette input').count()) === 1, HUNG_MS)
    await page.keyboard.type(label)
    await lib.until(async () => (await page.locator('.palette-item.active').innerText().catch(() => '')).includes(label), HUNG_MS)
    await page.keyboard.press('Enter')
  }
  check('no setup dialog on a fresh install', (await page.locator('.dialog', { hasText: 'Provider Setup' }).count()) === 0)
  check('welcome offers choosing agents', (await page.locator('.welcome-link', { hasText: 'Choose your coding agents' }).count()) === 1)
  await lib.openWorkspace(inv, page, ws)
  const banner = page.locator('.providers-banner')
  check('banner: no coding agents', /No coding agents are turned on/.test(await banner.innerText().catch(() => '')))
  await page.getByText('demo', { exact: true }).first().click()
  await lib.until(async () => (await page.locator('.project-header h1').innerText().catch(() => '')).includes('demo'), HUNG_MS)
  await page.screenshot({ path: path.join(scratch, 'pv-1-banner.png') })
  await banner.getByRole('button', { name: 'Choose providers' }).click()
  check('settings opens at Providers', !!(await lib.until(async () => (await page.locator('.settings-group h2', { hasText: 'Providers' }).count()) === 1, HUNG_MS)))
  await page.screenshot({ path: path.join(scratch, 'pv-2-providers.png') })
  const s0 = await inv('settings:get')
  check('fresh: Claude Code off', s0.providers['claude-code'].enabled === false)
  await page.locator('.provider-row', { hasText: 'Claude Code' }).locator('.switch, [role=switch], input[type=checkbox]').first().click()
  await lib.until(async () => (await inv('settings:get')).providers['claude-code'].enabled === true, lib.timing('hang.ui'))
  const s1 = await inv('settings:get')
  check('toggle turns Claude Code on', s1.providers['claude-code'].enabled === true)
  check('banner gone once on (Claude installed)', (await page.locator('.providers-banner').count()) === 0, await page.locator('.providers-banner').innerText().catch(() => ''))
  await page.locator('.settings-nav .row', { hasText: 'Claude Code' }).click()
  check('Claude page has its settings', !!(await lib.until(async () => (await page.locator('.setting', { hasText: 'Enable the Bypass permissions option' }).count()) === 1, HUNG_MS)))
  await page.screenshot({ path: path.join(scratch, 'pv-3-claude-page.png') })
  await inv('settings:update', { providers: { 'claude-code': { defaultModel: 'sonnet' } } })
  // Provider Setup
  await page.evaluate(() => window.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' })))
  await page.locator('.activitybar .activity, .activity-bar .activity').first().click().catch(() => undefined)
  await lib.until(async () => (await page.locator('.settings-nav').count()) === 0, HUNG_MS)
  await page.evaluate(() => (window).__cwRun?.('help.agentSetup'))
  // Open Provider Setup through the command palette.
  await fromPalette('Provider Setup')
  await lib.until(async () => (await page.locator('.dialog', { hasText: 'Provider Setup' }).count()) === 1, lib.timing('hang.ui'))
  const setup = page.locator('.dialog', { hasText: 'Provider Setup' })
  check('Provider Setup opens', (await setup.count()) === 1)
  check('Provider Setup shows Claude Code', /Claude Code \d/.test(await setup.innerText().catch(() => '')))
  await page.screenshot({ path: path.join(scratch, 'pv-4-setup.png') })
  await page.keyboard.press('Escape')
  await lib.until(async () => (await setup.count()) === 0, HUNG_MS)
  // Add Agent
  await inv('project:setActive', path.join(ws, 'demo'), true)
  await page.evaluate(() => window.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' })))
  await fromPalette('Add Agent…')
  await lib.until(async () => (await page.locator('.dialog', { hasText: 'Add an agent' }).count()) === 1, lib.timing('hang.ui'))
  const add = page.locator('.dialog', { hasText: 'Add an agent' })
  check('Add Agent has a connection choice, no coding agent choice (HI-2108)', (await add.locator('#add-agent-connection').count()) === 1 && (await add.locator('.provider-choice').count()) === 0)
  await page.screenshot({ path: path.join(scratch, 'pv-5-add-agent.png') })
  await page.keyboard.press('Escape')
  const readCfg = () => JSON.parse(fs.readFileSync(path.join(userData, 'config.json'), 'utf8'))
  await lib.until(() => readCfg().settings.claude?.defaultModel === 'sonnet', HUNG_MS)
  const cfg = readCfg()
  // Version 3 brought the provider settings; later versions keep the legacy block too.
  check('config saved as version 3 or later with the legacy block', cfg.version >= 3 && cfg.settings.claude?.defaultModel === 'sonnet', JSON.stringify(cfg.settings.claude))
  await app.close()
  console.log(results.join('\n'))
})().catch((e) => {
  console.error(e)
  console.log(results.join('\n'))
  process.exit(1)
})
